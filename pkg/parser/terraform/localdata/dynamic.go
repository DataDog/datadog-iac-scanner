package localdata

import (
	"github.com/DataDog/datadog-iac-scanner/pkg/parser/terraform/partial"
	"github.com/hashicorp/hcl/v2"
	"github.com/zclconf/go-cty/cty"
)

const blockTypeDynamic = "dynamic"

// dynamicHeader makes a body schema return the dynamic blocks beside its own.
var dynamicHeader = hcl.BlockHeaderSchema{Type: blockTypeDynamic, LabelNames: []string{"type"}}

var dynamicSchema = &hcl.BodySchema{
	Attributes: []hcl.AttributeSchema{{Name: "for_each"}, {Name: "iterator"}},
	Blocks:     []hcl.BlockHeaderSchema{{Type: "content"}},
}

// scopedBlock is a block to decode with the decoder that reads its expressions:
// one that binds the iterator when the block was generated by a dynamic block.
type scopedBlock struct {
	body hcl.Body
	d    decoder
}

// blocks returns the blocks of type typ in content, in source order, with those
// a dynamic block of that type generates. A dynamic block whose for_each does
// not resolve generates none and marks the document as incomplete.
func (d decoder) blocks(content *hcl.BodyContent, typ string) []scopedBlock {
	var out []scopedBlock
	for _, block := range content.Blocks {
		switch {
		case block.Type == typ:
			out = append(out, scopedBlock{body: block.Body, d: d})
		case block.Type == blockTypeDynamic && len(block.Labels) == 1 && block.Labels[0] == typ:
			out = append(out, d.expand(block, typ)...)
		}
	}
	return out
}

func (d decoder) expand(block *hcl.Block, typ string) []scopedBlock {
	dyn, _, _ := block.Body.PartialContent(dynamicSchema)
	if dyn == nil || len(dyn.Blocks) != 1 {
		*d.skipped = true
		return nil
	}
	forEach, ok := d.value(dyn.Attributes["for_each"])
	if ok {
		forEach, _ = forEach.UnmarkDeep()
	}
	if !ok || !forEach.IsWhollyKnown() || !forEach.CanIterateElements() {
		*d.skipped = true
		return nil
	}
	name := typ
	if attr := dyn.Attributes["iterator"]; attr != nil {
		if kw := hcl.ExprAsKeyword(attr.Expr); kw != "" {
			name = kw
		}
	}
	var out []scopedBlock
	for it := forEach.ElementIterator(); it.Next(); {
		key, value := it.Element()
		vars := map[string]cty.Value{name: cty.ObjectVal(map[string]cty.Value{"key": key, "value": value})}
		out = append(out, scopedBlock{body: dyn.Blocks[0].Body, d: d.bind(vars)})
	}
	return out
}

// bind returns a decoder evaluating in the scope of vars as well.
func (d decoder) bind(vars map[string]cty.Value) decoder {
	parent := d.eval
	return decoder{skipped: d.skipped, eval: func(expr hcl.Expression) (cty.Value, bool) {
		return parent(partial.Bind(expr, vars))
	}}
}
