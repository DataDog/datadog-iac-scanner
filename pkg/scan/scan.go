// Results represents a result generated by a single scan
type Results struct {
	Results        []model.Vulnerability
	ExtractedPaths provider.ExtractedPath
	Files          model.FileMetadatas
	FailedQueries  map[string]error
}

type executeScanParameters struct {
	services       []*runner.Service
	inspector      *engine.Inspector
	extractedPaths provider.ExtractedPath
	moduleCleanups []func()
	// Remote module files are tracked separately so repo-scoped filters do not apply.
	remoteModulePaths []string
}

func (c *Client) initScan(ctx context.Context) (*executeScanParameters, error) {
	contextLogger := logger.FromContext(ctx)

	var extractedPaths provider.ExtractedPath
	var filePlatform map[string]string
	if c.inMemory {
		// Content-push (server) mode: the file set is the pushed paths. Skip the
		// disk walk + analyzer.Analyze the CLI path runs (it reads the repo from
		// disk and mutates ScanParams.Platform). Platforms come from the request
		// (ScanParams.Platform); content is read through c.fsys.
		extractedPaths = provider.ExtractedPath{Path: c.inMemoryPaths}
	} else {
		paths, fp, err := c.prepareAndAnalyzePaths(ctx)
		if err != nil {
			contextLogger.Err(err).Msgf("failed to prepare and analyze paths %v", err)
			return nil, err
		}
		extractedPaths = paths
		filePlatform = fp
	}

	if len(extractedPaths.Path) == 0 {
		return nil, nil
	}

	paramsPlatforms := c.ScanParams.GetEffectivePlatforms()

	moduleCleanups, remoteModulePaths, remoteSourceDirs, err := c.resolveTerraformModulesForScan(ctx, paramsPlatforms, &extractedPaths)
	if err != nil {
		return nil, err
	}
	initSucceeded := false
	defer func() {
		if initSucceeded {
			return
		}
		for _, fn := range moduleCleanups {
			fn()
		}
	}()
	useDifferentPlatformQueries(&paramsPlatforms)
	querySource, err := c.createQuerySource(ctx, paramsPlatforms)
	if err != nil {
		contextLogger.Err(err).Msgf("Failed to create query source")
		return nil, err
	}

	queryFilter := c.createQueryFilter()

	contextLogger.Info().Msgf("Preparing to inspect query source %v", querySource)

	metrics.Metric.Start("get_queries")
	inspector, err := engine.NewInspector(ctx,
		querySource,
		engine.DefaultVulnerabilityBuilder,
		c.Tracker,
		queryFilter,
		c.ScanParams.Config.RuleConfigs,
		c.ScanParams.RepoPath,
		c.ScanParams.UseOldSeverities,
		true,
		c.ScanParams.ParallelScanFlag,
		c.ScanParams.FlagEvaluator,
		c.fsys,
		c.ScanParams.DisableRuleIsolation,
		c.ScanParams.UseRulesCache,
	)
	metrics.Metric.Stop()
	if err != nil {
		return nil, err
	}

	if len(remoteSourceDirs) > 0 {
		inspector.SetRemoteModuleDirectories(remoteSourceDirs)
	}
	inspector.SetExternalModulePaths(remoteModulePaths)

	contextLogger.Info().Msgf("Finished inspect query source %v", querySource)

	services, err := c.createService(
		ctx,
		inspector,
		extractedPaths.Path,
		remoteModulePaths,
		c.Tracker,
		c.Storage,
		paramsPlatforms,
		c.ScanParams.CloudProvider,
		c.FlagEvaluator,
		filePlatform,
	)
	if err != nil {
		contextLogger.Err(err).Msgf("failed to create service %v", err)
		return nil, err
	}

	initSucceeded = true
	return &executeScanParameters{
		services:          services,
		inspector:         inspector,
		remoteModulePaths: remoteModulePaths,
		extractedPaths:    extractedPaths,
		moduleCleanups:    moduleCleanups,
	}, nil
}

type resolvedEntry struct {
	res tfresolver.Resolution
	err error
}

type moduleGraphWalker struct {
	mu          sync.Mutex
	visited     map[string]bool
	resolved    map[string]resolvedEntry // persistent resolution cache (survives sf completion)
	paths       []string
	extractions map[string]model.ExtractedPathObject
	sourceDirs  map[string]string
	cleanups    []func()

	sf       singleflight.Group
	chain    tfresolver.Resolver
	maxDepth int

	parseMu    sync.Mutex
	parseCache map[string]map[string]tfmodules.ParsedModule
}

func newModuleGraphWalker(chain tfresolver.Resolver, maxDepth int) *moduleGraphWalker {
	return &moduleGraphWalker{
		visited:     make(map[string]bool),
		resolved:    make(map[string]resolvedEntry),
		extractions: make(map[string]model.ExtractedPathObject),
		sourceDirs:  make(map[string]string),
		chain:       chain,
		maxDepth:    maxDepth,
		parseCache:  make(map[string]map[string]tfmodules.ParsedModule),
	}
}

func (w *moduleGraphWalker) parseModulesInDir(
	ctx context.Context, dir string, allowedFiles map[string]bool,
) map[string]tfmodules.ParsedModule {
	key := filepath.Clean(dir) + "\x00" + allowedFilesCacheKey(allowedFiles)

	w.parseMu.Lock()
	if mods, ok := w.parseCache[key]; ok {
		w.parseMu.Unlock()
		return mods
	}
	w.parseMu.Unlock()

	var mods map[string]tfmodules.ParsedModule
	files, err := tfmodules.LoadTFFilesFromDir(dir)
	if err == nil && len(files) > 0 {
		withModuleParseSlot(ctx, func() {
			if parsed, parseErr := tfmodules.ParseTerraformModulesFromFiles(ctx, files, allowedFiles); parseErr == nil {
				mods = parsed
			}
		})
	}

	w.parseMu.Lock()
	w.parseCache[key] = mods
	w.parseMu.Unlock()
	return mods
}

func allowedFilesCacheKey(allowed map[string]bool) string {
	if allowed == nil {
		return "all"
	}
	paths := make([]string, 0, len(allowed))
	for p := range allowed {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	return strings.Join(paths, "\x00")
}

func (w *moduleGraphWalker) tryVisit(localPath string) bool {
	w.mu.Lock()
	defer w.mu.Unlock()
	if w.visited[localPath] {
		return false
	}
	w.visited[localPath] = true
	return true
}

func (w *moduleGraphWalker) addPaths(paths ...string) {
	if len(paths) == 0 {
		return
	}
	w.mu.Lock()
	w.paths = append(w.paths, paths...)
	w.mu.Unlock()
}

func (w *moduleGraphWalker) addExtraction(key string, val model.ExtractedPathObject) {
	w.mu.Lock()
	w.extractions[key] = val
	w.mu.Unlock()
}

func (w *moduleGraphWalker) addSourceDirs(entries map[string]string) {
	if len(entries) == 0 {
		return
	}
	w.mu.Lock()
	for k, v := range entries {
		w.sourceDirs[k] = v
	}
	w.mu.Unlock()
}

func (w *moduleGraphWalker) addCleanup(fn func()) {
	w.mu.Lock()
	w.cleanups = append(w.cleanups, fn)
	w.mu.Unlock()
}

func (w *moduleGraphWalker) resolveRemote(ctx context.Context, mod *tfmodules.ParsedModule) (tfresolver.Resolution, error) {
	resolveID := remoteResolveIdentity(mod)

	w.mu.Lock()
	if entry, ok := w.resolved[resolveID]; ok {
		w.mu.Unlock()
		return entry.res, entry.err
	}
	w.mu.Unlock()

	v, err, _ := w.sf.Do(resolveID, func() (interface{}, error) {
		// Re-check inside the closure: a concurrent goroutine may have finished
		// its singleflight call (and written to w.resolved) in the window between
		// our outer check above and this Do call.
		w.mu.Lock()
		if entry, ok := w.resolved[resolveID]; ok {
			w.mu.Unlock()
			return entry.res, entry.err
		}
		w.mu.Unlock()

		res, resolveErr := w.chain.Resolve(ctx, mod)
		w.mu.Lock()
		w.resolved[resolveID] = resolvedEntry{res: res, err: resolveErr}
		w.mu.Unlock()
		return res, resolveErr
	})
	if err != nil {
		return tfresolver.Resolution{}, err
	}
	return v.(tfresolver.Resolution), nil
}

var moduleTraversalConcurrency = tfresolver.FetchConcurrency

var moduleParseSem = make(chan struct{}, max(1, runtime.GOMAXPROCS(0)))

func withModuleParseSlot(ctx context.Context, fn func()) {
	select {
	case moduleParseSem <- struct{}{}:
		defer func() { <-moduleParseSem }()
		fn()
	case <-ctx.Done():
	}
}

func resolveRemoteModuleScanPaths(
	ctx context.Context,
	rootPaths []string,
	moduleDiscoveryPaths []string,
	chain tfresolver.Resolver,
	maxDepth int,
) (
	moduleScanPaths []string,
	moduleExtractions map[string]model.ExtractedPathObject,
	remoteSourceDirs map[string]string,
	cleanups []func(),
) {
	if maxDepth < 0 {
		return nil, nil, nil, nil
	}
	walker := newModuleGraphWalker(chain, maxDepth)
	seedGroups := walker.tfSeedGroups(ctx, rootPaths, moduleDiscoveryPaths)

	g, gCtx := errgroup.WithContext(ctx)
	g.SetLimit(runtime.GOMAXPROCS(0) * seedGroupConcurrencyFactor)
	for seedDir, allowedFiles := range seedGroups {
		g.Go(func() error {
			walker.traverse(gCtx, seedDir, allowedFiles, seedGroups, 0, false)
			return nil
		})
	}
	_ = g.Wait()

	return walker.paths, walker.extractions, walker.sourceDirs, walker.cleanups
}

func (w *moduleGraphWalker) tfSeedGroups(ctx context.Context, paths, moduleDiscoveryPaths []string) map[string]map[string]bool {
	allowedByDir := make(map[string]map[string]bool)
	for _, path := range moduleDiscoveryPaths {
		if !strings.HasSuffix(strings.ToLower(path), ".tf") {
			continue
		}
		dir := filepath.Dir(path)
		if allowedByDir[dir] == nil {
			allowedByDir[dir] = make(map[string]bool)
		}
		allowedByDir[dir][path] = true
	}
	groups := make(map[string]map[string]bool)
	for _, path := range paths {
		info, err := os.Stat(path)
		if err != nil {
			continue
		}
		if !info.IsDir() {
			if !strings.HasSuffix(strings.ToLower(path), ".tf") {
				continue
			}
			dir := filepath.Dir(path)
			if groups[dir] == nil {
				groups[dir] = make(map[string]bool)
			}
			groups[dir][path] = true
			continue
		}
		if len(moduleDiscoveryPaths) == 0 {
			groups[path] = nil
			continue
		}
		for dir, allowedFiles := range allowedByDir {
			if pathContainsDir(path, dir) {
				groups[dir] = allowedFiles
			}
		}
	}
	for child := range w.localModuleChildDirs(ctx, groups) {
		delete(groups, child)
	}
	return groups
}

func pathContainsDir(root, dir string) bool {
	rel, err := filepath.Rel(filepath.Clean(root), filepath.Clean(dir))
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(os.PathSeparator))
}

func (w *moduleGraphWalker) localModuleChildDirs(ctx context.Context, groups map[string]map[string]bool) map[string]bool {
	children := make(map[string]bool)
	for dir, allowedFiles := range groups {
		mods := w.parseModulesInDir(ctx, dir, allowedFiles)
		for src := range mods {
			if mods[src].IsLocal && groups[filepath.Clean(mods[src].AbsSource)] != nil {
				children[filepath.Clean(mods[src].AbsSource)] = true
			}
		}
	}
	return children
}

func (w *moduleGraphWalker) traverse(
	ctx context.Context,
	seed string,
	allowedFiles map[string]bool,
	repoAllowedDirs map[string]map[string]bool,
	depth int,
	inRemoteTree bool,
) {
	if w.maxDepth <= 0 || depth >= w.maxDepth {
		return
	}
	mods := w.parseModulesInDir(ctx, seed, allowedFiles)
	if mods == nil {
		return
	}

	for src := range mods {
		if !mods[src].IsLocal {
			continue
		}
		localDir := mods[src].AbsSource
		if localDir == "" {
			continue
		}
		childAllowedFiles := map[string]bool(nil)
		if !inRemoteTree {
			var ok bool
			childAllowedFiles, ok = repoAllowedDirs[filepath.Clean(localDir)]
			if !ok {
				continue
			}
		}
		if !w.tryVisit(localDir) {
			continue
		}
		// Remote-tree local modules are not covered by the repository scan.
		if inRemoteTree {
			w.addPaths(flatTFFilePaths(localDir)...)
		}
		w.traverse(ctx, localDir, childAllowedFiles, repoAllowedDirs, depth+1, inRemoteTree)
	}

	w.traverseRemoteMods(ctx, mods, repoAllowedDirs, depth)
}

// remoteModGroup groups module call sites that resolve to the same content
// (same resolve identity) so we spawn one goroutine per unique resolution
// instead of one per call site.
type remoteModGroup struct {
	representative *tfmodules.ParsedModule   // used for the resolve call
	callers        []*tfmodules.ParsedModule  // all call sites (for addSourceDirs)
}

func (w *moduleGraphWalker) traverseRemoteMods(
	ctx context.Context,
	mods map[string]tfmodules.ParsedModule,
	repoAllowedDirs map[string]map[string]bool,
	depth int,
) {
	// Two-phase deduplication before spawning goroutines:
	//
	// Phase 1 (pre-check): modules whose resolve identity is already present in
	// w.resolved were fetched by an earlier traversal.  Register their source
	// directories synchronously without spawning a goroutine.  tryVisit will
	// return false for them so no recursive traversal is needed either.
	//
	// Phase 2 (grouping): remaining modules are grouped by identity so that a
	// single goroutine drives the resolve and every caller in the group receives
	// the result, eliminating contention on the singleflight inside resolveRemote.
	groups := make(map[string]*remoteModGroup)
	for src := range mods {
		if mods[src].IsLocal {
			continue
		}
		m := mods[src]
		id := remoteResolveIdentity(&m)

		// Phase 1: cheap cache hit — register source dirs and skip the goroutine.
		w.mu.Lock()
		cached, hit := w.resolved[id]
		w.mu.Unlock()
		if hit {
			if cached.err == nil && cached.res.LocalPath != "" {
				root := moduleCallRoot(&m)
				w.addSourceDirs(map[string]string{
					engine.RemoteModuleKey(root, m.Source, m.Version):             cached.res.LocalPath,
					engine.RemoteModuleCallKey(root, m.Source, m.Version, m.Name): cached.res.LocalPath,
					engine.RemoteModuleCallKey(root, m.Source, "", m.Name):        cached.res.LocalPath,
				})
			}
			continue
		}

		// Phase 2: new identity — include in goroutine fan-out.
		if g, ok := groups[id]; ok {
			g.callers = append(g.callers, &m)
		} else {
			groups[id] = &remoteModGroup{representative: &m, callers: []*tfmodules.ParsedModule{&m}}
		}
	}
	if len(groups) == 0 {
		return
	}

	contextLogger := logger.FromContext(ctx)
	eg, gCtx := errgroup.WithContext(ctx)
	eg.SetLimit(moduleTraversalConcurrency)
	for _, grp := range groups {
		eg.Go(func() error {
			rep := grp.representative
			contextLogger.Debug().Msgf("Fetching remote Terraform module %q", rep.Source)
			res, resolveErr := w.resolveRemote(gCtx, rep)
			if resolveErr != nil {
				contextLogger.Warn().Err(resolveErr).Msgf("Failed to resolve remote Terraform module %q", rep.Source)
				return nil
			}
			if res.LocalPath == "" {
				contextLogger.Warn().Msgf("Resolved remote Terraform module %q without a local path", rep.Source)
				return nil
			}
			contextLogger.Info().Msgf("Fetched remote Terraform module %q", rep.Source)

			// Register caller-specific source-dir keys for every call site in the group.
			// These keys differ by caller root and module label even for the same resolved path.
			sourceDirs := make(map[string]string, len(grp.callers)*3)
			for _, mod := range grp.callers {
				root := moduleCallRoot(mod)
				sourceDirs[engine.RemoteModuleKey(root, mod.Source, mod.Version)] = res.LocalPath
				sourceDirs[engine.RemoteModuleCallKey(root, mod.Source, mod.Version, mod.Name)] = res.LocalPath
				sourceDirs[engine.RemoteModuleCallKey(root, mod.Source, "", mod.Name)] = res.LocalPath
			}
			w.addSourceDirs(sourceDirs)

			if !w.tryVisit(res.LocalPath) {
				return nil
			}
			if res.Cleanup != nil {
				w.addCleanup(res.Cleanup)
			}
			w.addPaths(flatTFFilePaths(res.LocalPath)...)
			w.addExtraction(res.LocalPath, model.ExtractedPathObject{
				Path:      canonicalModuleURL(rep.Source, rep.Version),
				LocalPath: false,
			})
			w.traverse(gCtx, res.LocalPath, nil, repoAllowedDirs, depth+1, true)
			return nil
		})
	}
	_ = eg.Wait()
}

func moduleCallRoot(mod *tfmodules.ParsedModule) string {
	if mod.FileName == "" {
		return "."
	}
	return filepath.Clean(filepath.Dir(mod.FileName))
}

func remoteResolveIdentity(mod *tfmodules.ParsedModule) string {
	sourceType, _ := tfmodules.DetectModuleSourceType(mod.Source)
	// Versionless registry sources may resolve to different versions per call site.
	if sourceType == moduleSourceRegistry && mod.Version == "" {
		return engine.RemoteModuleCallKey(moduleCallRoot(mod), mod.Source, mod.Version, mod.Name)
	}
	// Pinned git modules: fold transport spellings to (repo, ref, subdir).
	if key, ok := tfresolver.GitModuleResolveKey(mod.Source, mod.Version); ok {
		return key
	}
	// Registry pins and other sources: canonicalGitModuleSource folds ".git" spellings.
	return canonicalGitModuleSource(mod.Source) + "\x00" + strings.TrimSpace(mod.Version)
}

func flatTFFilePaths(dir string) []string {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	var paths []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		if strings.HasSuffix(strings.ToLower(name), ".tf") {
			paths = append(paths, filepath.Join(dir, name))
		}
	}
	return paths
}

// canonicalGitModuleSource folds ".git" spellings so identical modules share one resolve identity.
func canonicalGitModuleSource(moduleSource string) string {
	s := strings.TrimSpace(moduleSource)
	switch {
	case strings.Contains(s, ".git//"):
		return strings.Replace(s, ".git//", "//", 1)
	case strings.Contains(s, ".git?"):
		return strings.Replace(s, ".git?", "?", 1)
	case strings.HasSuffix(s, ".git"):
		return strings.TrimSuffix(s, ".git")
	}
	return s
}

func canonicalModuleURL(moduleSource, version string) string {
	out := canonicalGitModuleSource(moduleSource)
	st, scope := tfmodules.DetectModuleSourceType(out)
	if st == moduleSourceRegistry && scope == "public" {
		// Short form → registry.terraform.io/…
		if !strings.HasPrefix(out, "registry.terraform.io/") {
			out = "registry.terraform.io/" + out
		}
	}
	// Strip userinfo first so the @ version suffix is unambiguous.
	if idx := strings.Index(out, "@"); idx != -1 {
		if schemeEnd := strings.Index(out, "://"); schemeEnd != -1 && schemeEnd < idx {
			out = out[:schemeEnd+3] + out[idx+1:]
		}
	}
	if version != "" {
		out = out + "@" + version
	}
	return out
}

// buildModuleResolverChain returns:
//
//	local → .terraform/modules → manifest → LocalGitRef → BareGit → GoGetter
func (c *Client) buildModuleResolverChain(ctx context.Context, moduleDiscoveryPaths []string) *tfresolver.ChainResolver {
	contextLogger := logger.FromContext(ctx)

	resolvers := []tfresolver.Resolver{
		tfresolver.LocalResolver{},
		&tfresolver.DotTerraformResolver{RootDirs: dotTerraformRootDirs(moduleDiscoveryPaths)},
	}

	if c.ScanParams.ModulesManifestPath != "" {
		manifest, err := tfresolver.LoadManifest(c.ScanParams.ModulesManifestPath)
		if err != nil {
			contextLogger.Warn().Err(err).
				Msgf("Failed to load modules manifest %q; remote modules from manifest will be unresolved",
					c.ScanParams.ModulesManifestPath)
		} else {
			resolvers = append(resolvers, tfresolver.NewPrefetchedResolver(manifest))
		}
	}

	if !c.ScanParams.NoRemoteModules {
		resolvers = append(resolvers,
			tfresolver.NewLocalGitRefResolver(c.ScanParams.Path, ""),
			tfresolver.NewBareGitResolver(""),
		)
	}

	ggCfg := tfresolver.NewGoGetterConfig()
	ggCfg.Disabled = c.ScanParams.NoRemoteModules
	if t := c.ScanParams.ModuleFetchTimeout; t > 0 {
		ggCfg.FetchTimeout = t
		// Recreate the registry cache with the user-supplied timeout so the HTTP
		// client it holds respects the same deadline as go-getter fetches.
		ggCfg.RegistryCache = tfresolver.NewRegistryCache(ggCfg.FetchTimeout)
	}
	ggCfg.MaxTotalBytes = c.ScanParams.MaxModuleBytesTotal
	ggCfg.HostAllowlist = c.ScanParams.ModuleHostAllowlist

	if !ggCfg.Disabled {
		cache, err := tfresolver.NewModuleCache()
		if err != nil {
			contextLogger.Warn().Err(err).Msg("Module disk cache unavailable; fetched modules will not be cached")
		} else {
			ggCfg.Cache = cache
		}
	}

	resolvers = append(resolvers, tfresolver.NewGoGetterResolver(ggCfg))
	return tfresolver.NewChainResolver(resolvers...)
}

func dotTerraformRootDirs(paths []string) []string {
	seen := make(map[string]bool, len(paths))
	roots := make([]string, 0, len(paths))
	for _, p := range paths {
		root := terraformRootDir(p)
		if root == "" || seen[root] {
			continue
		}
		seen[root] = true
		roots = append(roots, root)
	}
	return roots
}

func terraformRootDir(path string) string {
	info, err := os.Stat(path)
	if err == nil && !info.IsDir() {
		path = filepath.Dir(path)
	}
	clean := filepath.Clean(path)
	for {
		if hasTerraformModulesManifest(clean) {
			return clean
		}
		parent := filepath.Dir(clean)
		if parent == clean {
			return filepath.Clean(path)
		}
		clean = parent
	}
}

func hasTerraformModulesManifest(dir string) bool {
	_, err := os.Stat(filepath.Join(dir, ".terraform", "modules", "modules.json"))
	return err == nil
}

// shouldPreScanTerraformModules reports whether initScan should walk and resolve
// module sources before the main scan. Remote network fetches are gated separately
// by NoRemoteModules; when that flag is set, only manifest and .terraform/modules
// offline sources justify the pre-scan graph walk.
func (c *Client) shouldPreScanTerraformModules(scanPaths []string) bool {
	if !c.ScanParams.NoRemoteModules {
		return true
	}
	if c.ScanParams.ModulesManifestPath != "" {
		return true
	}
	for _, root := range dotTerraformRootDirs(scanPaths) {
		if hasTerraformModulesManifest(root) {
			return true
		}
	}
	return false
}

func (c *Client) resolveTerraformModulesForScan(
	ctx context.Context,
	paramsPlatforms []string,
	extractedPaths *provider.ExtractedPath,
) (moduleCleanups []func(), remoteModulePaths []string, remoteSourceDirs map[string]string, err error) {
	if !platformsIncludeTerraform(paramsPlatforms) || !c.shouldPreScanTerraformModules(extractedPaths.Path) {
		return nil, nil, nil, nil
	}

	contextLogger := logger.FromContext(ctx)
	filteredFilesSource, err := c.getFileSystemSourceProvider(ctx, extractedPaths.Path, nil)
	if err != nil {
		return nil, nil, nil, err
	}
	moduleDiscoveryPaths, err := filteredFilesSource.TerraformFiles(ctx)
	if err != nil {
		return nil, nil, nil, err
	}
	chain := c.buildModuleResolverChain(ctx, moduleDiscoveryPaths)

	if c.ScanParams.NoRemoteModules {
		contextLogger.Debug().Msg("Resolving Terraform modules from local, manifest, or .terraform/modules sources")
	} else {
		contextLogger.Info().Msg("Resolving remote Terraform modules...")
	}
	maxDepth := c.ScanParams.ModuleMaxDepth
	moduleScanPaths, moduleExtractions, sourceDirs, cleanups := resolveRemoteModuleScanPaths(
		ctx, extractedPaths.Path, moduleDiscoveryPaths, chain, maxDepth)
	if len(moduleScanPaths) > 0 {
		contextLogger.Info().Msgf("Adding %d remote module file(s) to scan", len(moduleScanPaths))
		remoteModulePaths = moduleScanPaths
		for k, v := range moduleExtractions {
			extractedPaths.ExtractionMap[k] = v
		}
	}
	return cleanups, remoteModulePaths, sourceDirs, nil
}

func (c *Client) createQuerySource(ctx context.Context, paramsPlatforms []string) (source.QueriesSource, error) {
	if c.querySourceFactory != nil {
		return c.querySourceFactory(ctx, paramsPlatforms)
	}
	fss := source.NewFilesystemSource(
		ctx,
		c.ScanParams.QueriesPath,
		paramsPlatforms,
		c.ScanParams.CloudProvider,
		c.ScanParams.LibrariesPath,
		c.ScanParams.ExperimentalQueries)
	if c.ScanParams.ChangedDefaultQueryPath {
		if c.ScanParams.ChangedDefaultLibrariesPath {
			// Explicit --libraries-path provided: use local libraries from disk.
			return fss, nil
		}
		// Local query path but no explicit libraries path: fetch libraries from the backend.
		libSource, err := source.NewDatadogSource(datadog.NewDatadogClient())
		if err != nil {
			return nil, err
		}
		return source.NewFilesystemSourceWithLibraryOverride(fss, libSource), nil
	}
	options := []source.DatadogSourceOption{
		source.WithWantedPlatforms(paramsPlatforms),
		source.WithWantedCloudProviders(c.ScanParams.CloudProvider),
	}
	if c.ScanParams.ChangedDefaultLibrariesPath {
		options = append(options, source.WithLibrarySource(fss))
	}
	return source.NewDatadogSource(
		datadog.NewDatadogClient(),
		options...,
	)
}

func (c *Client) executeScan(ctx context.Context) (*Results, error) {
	contextLogger := logger.FromContext(ctx)
	executeScanParameters, err := c.initScan(ctx)

	if err != nil {
		contextLogger.Err(err).Msgf("failed to execute scan %v", err)
		return nil, err
	}

	if executeScanParameters == nil {
		return nil, nil
	}

	defer func() {
		for _, fn := range executeScanParameters.moduleCleanups {
			fn()
		}
	}()

	contextLogger.Info().Msg("Scan initialized")

	contextLogger.Info().Msgf("Preparing to scan")

	if err = scanner.PrepareAndScan(
		ctx,
		c.ScanParams.ScanID, c.ScanParams.OpenAPIResolveReferences, c.ScanParams.MaxResolverDepth,
		executeScanParameters.services, c.FlagEvaluator); err != nil {
		contextLogger.Err(err).Msgf("failed to prepare and scan %v", err)
		return nil, err
	}

	contextLogger.Info().Msg("Scan finished")

	failedQueries := executeScanParameters.inspector.GetFailedQueries()

	results, err := c.Storage.GetVulnerabilities(ctx, c.ScanParams.ScanID)
	if err != nil {
		contextLogger.Err(err).Msgf("failed to get vulns %v", err)
		return nil, err
	}

	files, err := c.Storage.GetFiles(ctx, c.ScanParams.ScanID)
	if err != nil {
		contextLogger.Err(err).Msgf("failed to get files %v", err)
		return nil, err
	}

	return &Results{
		Results:        results,
		ExtractedPaths: executeScanParameters.extractedPaths,
		Files:          files,
		FailedQueries:  failedQueries,
	}, nil
}

func platformsIncludeTerraform(platforms []string) bool {
	for _, p := range platforms {
		if strings.EqualFold(p, "terraform") {
			return true
		}
	}
	return false
}

func useDifferentPlatformQueries(platforms *[]string) {
	hasBicep := false
	hasARM := false
	for _, platform := range *platforms {
		if platform == "bicep" {
			hasBicep = true
		}
		if platform == "azureresourcemanager" {
			hasARM = true
		}
		if hasARM && hasBicep {
			break
		}
	}

	if hasBicep && !hasARM {
		*platforms = append(*platforms, "azureresourcemanager")
	}
}

func (c *Client) createQueryFilter() *source.QueryInspectorParameters {
	excludeQueries := source.QueryFilter{
		ByIDs:        c.ScanParams.Config.IgnoreRules,
		ByCategories: c.ScanParams.Config.IgnoreCategories,
		BySeverities: c.ScanParams.Config.IgnoreSeverities,
	}
	includeQueries := source.QueryFilter{
		ByIDs:        c.ScanParams.Config.OnlyRules,
		ByCategories: c.ScanParams.Config.OnlyCategories,
		BySeverities: c.ScanParams.Config.OnlySeverities,
	}

	queryFilter := source.QueryInspectorParameters{
		ExcludeQueries:      excludeQueries,
		IncludeQueries:      includeQueries,
		ExperimentalQueries: c.ScanParams.ExperimentalQueries,
		InputDataPath:       c.ScanParams.InputData,
		BomQueries:          c.ScanParams.BillOfMaterials,
		FlagEvaluator:       c.FlagEvaluator,
	}

	return &queryFilter
}

func (c *Client) createService(
	ctx context.Context,
	inspector *engine.Inspector,
	paths []string,
	remoteModulePaths []string,
	t runner.Tracker,
	store runner.Storage,
	types []string,
	cloudProviders []string,
	flagEvaluator featureflags.FlagEvaluator,
	filePlatform map[string]string) ([]*runner.Service, error) {
	var filesSource provider.SourceProvider
	if c.inMemory {
		// Content-push mode: serve the pushed files from the in-memory FS instead
		// of walking the disk. No symlink/SameFile handling and no Helm chart
		// discovery occur (the resolverSink is never invoked).
		filesSource = provider.NewMemorySourceProvider(c.fsys, paths,
			c.ScanParams.Config.IgnorePaths, c.ScanParams.Config.OnlyPaths)
	} else {
		fsSource, err := c.getFileSystemSourceProvider(ctx, paths, remoteModulePaths)
		if err != nil {
			return nil, err
		}
		if len(c.walkInventory) > 0 {
			fsSource.SetPrebuiltWalk(c.walkInventory, c.chartRoots, c.contentCache)
		}
		filesSource = fsSource
	}

	combinedParserBuilder := parser.NewBuilder(ctx).
		WithFS(c.fsys).
		Add(&yamlParser.Parser{}).
		Add(terraformParser.NewDefaultWithParams(c.fsys, c.ScanParams.TerraformVarsPath, c.ScanParams.SCIInfo)).
		Add(&bicepParser.Parser{}).
		Add(&cicdParser.Parser{}).
		Add(&dockerParser.Parser{}).
		Add(&protoParser.Parser{}).
		Add(&buildahParser.Parser{}).
		Add(&ansibleConfigParser.Parser{}).
		Add(&ansibleHostsParser.Parser{})

	if c.ScanParams.ShouldScanTfPlans {
		combinedParserBuilder.Add(&jsonParser.Parser{})
	}

	combinedParser, err := combinedParserBuilder.Build(types, cloudProviders)
	if err != nil {
		return nil, err
	}

	// combinedResolver to be used to resolve files and templates
	builder := resolver.NewBuilder()
	if flagEvaluator.EvaluateWithOrg(featureflags.IacEnableKicsHelmResolver) {
		builder = builder.Add(ctx, &helm.Resolver{})
	}
	combinedResolver, err := builder.
		Build(ctx)
	if err != nil {
		return nil, err
	}

	services := make([]*runner.Service, 0, len(combinedParser))

	for _, p := range combinedParser {
		services = append(
			services,
			&runner.Service{
				SourceProvider: filesSource,
				Storage:        store,
				Parser:         p,
				Inspector:      inspector,
				Tracker:        t,
				Resolver:       combinedResolver,
				MaxFileSize:    c.ScanParams.MaxFileSizeFlag,
				Platforms:      types,
				FilePlatform:   filePlatform,
			},
		)
	}
	return services, nil
}

// getFileSystemSourceProvider applies repo path filters; remote module paths bypass them.
func (c *Client) getFileSystemSourceProvider(
	ctx context.Context, paths, remoteModulePaths []string,
) (*provider.FileSystemSourceProvider, error) {
	var excludePaths []string
	if c.ScanParams.PayloadPath != "" {
		excludePaths = append(excludePaths, c.ScanParams.PayloadPath)
	}
	if len(c.ScanParams.Config.IgnorePaths) > 0 {
		excludePaths = append(excludePaths, c.ScanParams.Config.IgnorePaths...)
	}

	filesSource, err := provider.NewFileSystemSourceProvider(ctx, paths, excludePaths, c.ScanParams.Config.OnlyPaths)
	if err != nil {
		return nil, err
	}
	if len(remoteModulePaths) > 0 {
		filesSource.AddUnfilteredPaths(remoteModulePaths)
	}
	return filesSource, nil
}
