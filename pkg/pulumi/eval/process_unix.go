package eval

import (
	"errors"
	"os/exec"
	"syscall"
)

// osSupported reports whether this OS can run evaluations.
const osSupported = true

// setProcessGroup starts the command in its own process group, so that the
// program and everything it starts can be killed together.
func setProcessGroup(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
}

// killProcessGroup kills the command's whole process group.
func killProcessGroup(cmd *exec.Cmd) error {
	if cmd.Process == nil {
		return nil
	}
	err := syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL)
	if errors.Is(err, syscall.ESRCH) {
		return nil
	}
	return err
}
