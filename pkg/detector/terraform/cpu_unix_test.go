package terraform

import (
	"syscall"
	"time"
)

// processCPU is the CPU time the process has used, which other processes on
// the machine do not inflate the way they inflate wall time.
func processCPU() time.Duration {
	var usage syscall.Rusage
	if err := syscall.Getrusage(syscall.RUSAGE_SELF, &usage); err != nil {
		return 0
	}
	return time.Duration(usage.Utime.Nano() + usage.Stime.Nano())
}
